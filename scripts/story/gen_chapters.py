def m(line: str, mark: str, yes: str, no: str = "") -> str:
    return f"{{?{line}.{mark}:{yes}|{no}}}" if no else f"{{?{line}.{mark}:{yes}}}"


def w(flag: str, yes: str, no: str = "") -> str:
    return f"{{?世.{flag}:{yes}|{no}}}" if no else f"{{?世.{flag}:{yes}}}"


def h(beat: str, result: str, yes: str, no: str = "") -> str:
    return f"{{?史.{beat}={result}:{yes}|{no}}}" if no else f"{{?史.{beat}={result}:{yes}}}"


def at(*locs: str) -> dict:
    return {"locations": list(locs)}


def act(sid: str, eid: str, where: dict, hint: str) -> dict:
    """一幕：人到了那裡，選單上（與章回卡上）多一顆「未了之事」，按了才端出來（immediate 關著：不搶走那裡別的事）。"""
    return {"id": sid, "event": eid, "where": where, "hint": hint, "immediate": False}


def wait(beat_title: str, routes: list[tuple[str, str]], default: str) -> dict:
    return {"id": "wait", "kind": "task", "task": "chapter_beat", "hint": f"等{beat_title}",
            "routes": [{"when": {mark: 1}, "go": go} for mark, go in routes], "next": default}


def ending(eid: str, title: str, text: str, annal: str, effect: dict | None = None, failed: bool = False) -> dict:
    out = {"id": eid, "title": title, "text": text, "annal": annal, "effect": effect if effect is not None else REWARD}
    if failed:
        out["failed"] = True
    return out


def missed(title: str, text: str, annal: str) -> dict:
    return ending("missed", "沒趕上", text, annal, effect={}, failed=True)


def chapter(lid: str, side: str, no: int, title: str, intro: str, beat: str, stages: list, endings: list, *,
            after: list[str] | None = None, after_beat: str | None = None, sway: str | None = None,
            sway_marks: dict | None = None, side_marks: dict | None = None) -> None:
    spec = {"side": side, "no": no, "beat": beat}
    if after:
        spec["after"] = after
    if after_beat:
        spec["after_beat"] = after_beat
    if sway:
        spec["sway"] = sway
    if sway_marks:
        spec["sway_marks"] = sway_marks
    if side_marks:
        spec["side_marks"] = side_marks
    LINES.append({"id": lid, "title": title, "kind": "章回", "intro": intro, "chapter": spec, "stages": stages,
                  "endings": endings, "unfinished": f"{{name}}手上的「{title}」到季末還沒有了結。"})


def go(line: str, marks: dict | None = None, to: str | None = None) -> dict:
    return step(line, marks or {}, to)


def labor(line: str, eid: str, title: str, image: str, text: str, fight: tuple[str, str], who: str, to: str = "wait") -> dict:
    """三選一做一件（設計稿第四節：讓不愛打的人也做得完）：交一份軍需、出去打一場（輸了也算做了）、替人跑一趟。"""
    label, squad = fight
    return event(eid, title, image, text, [
        choice(f"交一份軍需（銀兩 {SILVER}）", eff("你把銀子交給管軍需的人。他在冊子上記了一筆。", go(line, {"軍需": 1}, to), stats={"silver": -SILVER}),
               condition={"min_stats": {"silver": SILVER}}),
        choice(label, eff("你打完回來，身上多了幾道口子。", go(line, {"出戰": 1}, to)), combat=squad,
               fail=eff("你沒打贏，被人拖了回來。可是該清的路，清出了一半。", go(line, {"出戰": 1}, to))),
        choice(f"替{who}跑一趟（體力 {STAMINA}）", eff("你跑了一趟，回來的時候天已經黑了。", go(line, {"跑腿": 1}, to), stamina=-STAMINA)),
    ])


