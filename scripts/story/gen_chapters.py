"""章回主線（企劃者 2026-10-29 同意的長版：「長社那一夜」第一、二回、「宛城到廣宗」第三到五回）寫成內容：
content/events/chapter_main.json、storylines.json 的十五回（官軍、黃巾、地方豪強各五回；tianxia/chapters.py）。
用法：python gen_chapters.py <repo 根目錄>

寫法照長篇奇事（storykit）：一幕一則事件，選項記號、往哪一段；最後一段一律是 wait（等那一件大事結算），結局照結果的記號
（「果成」「果不成」「果guan」「果huang」）分。文字裡 {?<線>.<記號>:…|…} 讀自己的記號，{?世.<旗標>:…} 讀全服的世界旗標
（別的陣營做了什麼），{?史.<大事>=<結果>:…} 讀時刻表那一件大事的結果。數字（銀兩、體力、份量）都是【預設】。"""
