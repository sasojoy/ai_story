def m(mark: str, yes: str, no: str = "") -> str:
    return f"{{?{L}.{mark}:{yes}|{no}}}" if no else f"{{?{L}.{mark}:{yes}}}"


def said_after(prior: list[str], n: int = 0) -> str:
    """自己寫的第幾句：前面那幾幕（prior）寫過幾句就往後數幾格（沒寫的不佔位子）。"""
    if not prior:
        return f"{{said:{L}.{n}}}"
    return m(prior[0], said_after(prior[1:], n + 1), said_after(prior[1:], n))


def has(marks: dict) -> dict:
    return {"story_marks": {f"{L}:{k}": v for k, v in marks.items()}}


def lacks(*marks: str) -> dict:
    return {"story_marks_max": {f"{L}:{k}": 0 for k in marks}}


