def middle(i: int = 0, room: int = 2) -> str:
    if i == len(MIDDLE) or room == 0:
        return ""
    cond, text = MIDDLE[i]
    rest = middle(i + 1, room)
    return cond(text + middle(i + 1, room - 1), rest) if rest else cond(text + middle(i + 1, room - 1), "")


